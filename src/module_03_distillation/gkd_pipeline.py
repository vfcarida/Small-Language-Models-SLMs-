class VLLMTeacherOracle:
    """
    Remote API interface for the Teacher model served via vLLM.
    
    EDUCATIONAL CONCERN — DECOUPLED ARCHITECTURE:
        A strong teacher model (e.g., Llama-3.1-70B) requires ~140GB VRAM in BF16 precision.
        The student (e.g., Qwen-1.5B) fits easily in ~3GB VRAM.
        Running both on the same local GPU for live distillation triggers severe memory saturation.
        
        Solution:
        1. Serve the teacher model on a remote cluster (e.g. using vLLM for high throughput).
        2. Execute the student model locally, sending generation sequences to the teacher via API requests.
        3. Retrieve log probabilities from the remote teacher.
        4. Calculate KL Divergence loss locally on the student node.
    """
    def __init__(self, endpoint_url: str, timeout: int = 10, max_retries: int = 3, api_key: Optional[str] = None):
        self.endpoint_url = endpoint_url
        self.timeout = timeout
        self.max_retries = max_retries
        self.headers = {"Content-Type": "application/json"}
        if api_key:
            self.headers["Authorization"] = f"Bearer {api_key}"
        logger.info(f"Connected to Remote Teacher Oracle at: {endpoint_url}")

    def get_logprobs(self, prompt: str, generated_text: str) -> Dict[str, Any]:
        """
        Fetches token log-probabilities from the remote teacher instance for the target generated text.
        
        Args:
            prompt: Original prompt context prefix.
            generated_text: Suffix generated by the student.
            
        Returns:
            Dict: Log probabilities structure returned by the endpoint.
        """
        payload = {
            "prompt": prompt,
            "text": generated_text,
            "max_tokens": 1,
            "logprobs": 5, 
            "echo": True
        }
        
        backoff = 1.0
        for attempt in range(1, self.max_retries + 1):
            try:
                response = requests.post(
                    f"{self.endpoint_url}/v1/completions",
                    json=payload,
                    headers=self.headers,
                    timeout=self.timeout
                )
                response.raise_for_status()
                return response.json()
            except requests.exceptions.RequestException as e:
                logger.warning(
                    f"Communication attempt {attempt}/{self.max_retries} with vLLM Teacher failed: {e}. "
                    f"Retrying after {backoff} seconds..."
                )
                if attempt == self.max_retries:
                    logger.error("Maximum vLLM communication retries reached. Distillation step failed.")
                    raise
                time.sleep(backoff)
                backoff *= 2.0


def explain_kl_divergence():
    """
    Explains the mathematical logic behind knowledge distillation using KL Divergence.
    
    MATHEMATICAL THEORY:
        During standard Supervised Fine-Tuning (SFT), cross-entropy operates on hard labels (one-hot vectors).
        During Distillation, we leverage soft labels from the teacher.
        
        The rich soft probability distribution contains "Dark Knowledge" (Hinton).
        It highlights relative semantic similarities among candidate tokens.
        
        Kullback-Leibler (KL) Divergence Formula:
        
            D_KL(P || Q) = Σ P(x) * log( P(x) / Q(x) )
            
        Where:
        - P represents the Teacher's soft distribution.
        - Q represents the Student's active distribution.
    """
    logger.info("\n" + "=" * 60)
    logger.info("THEORY: Kullback-Leibler (KL) Divergence and Soft Labels")
    logger.info("=" * 60)
    
    classes = ["Paris", "Lyon", "London", "Apple"]
    
    # Soft labels from teacher
    teacher_probs = torch.tensor([0.80, 0.15, 0.04, 0.01])
    # Distorted prediction from student
    student_probs = torch.tensor([0.25, 0.25, 0.25, 0.25])
    
    logger.info(f"Token Classes:          {classes}")
    logger.info(f"Teacher Soft Label:    {teacher_probs.tolist()}")
    logger.info(f"Student Probabilities: {student_probs.tolist()}")
    
    log_student = torch.log(student_probs)
    kl_loss = F.kl_div(log_student, teacher_probs, reduction='sum')
    
    logger.info(f"\nCalculated KL Divergence Loss: {kl_loss.item():.4f}")
    logger.info("The optimizer adjusts the student weights to align distribution output with the teacher.")


def run_gkd_pipeline(config: Dict[str, Any]):
    """
    Runs the Generalized Knowledge Distillation pipeline.
    
    Args:
        config: Central configuration dictionary.
    """
    logger.info("\n" + "=" * 60)
    logger.info("STARTING GENERALIZED KNOWLEDGE DISTILLATION (GKD) PIPELINE")
    logger.info("=" * 60)
    
    gkd_cfg = config.get("distillation", {})
    output_dir = "./results/gkd_output"
    os.makedirs(output_dir, exist_ok=True)
    
    model_id = config.get("model", {}).get("base_model_id", "Qwen/Qwen2.5-1.5B")
    
    tokenizer = AutoTokenizer.from_pretrained(model_id, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
        
    logger.info(f"Loading Student model: {model_id}")
    student_model = AutoModelForCausalLM.from_pretrained(
        model_id, device_map="auto", torch_dtype=torch.bfloat16
    )
    
    # For local demonstration, wrap student model as a mock teacher
    logger.info("Instantiating Local Mock Teacher for local validation run...")
    mock_teacher = student_model 
    
    train_dataset, _ = load_and_prepare_dataset(
        max_samples=100, format_fn="alpaca"
    )
    
    logger.info("\n⚙️ Tuning GKD Distillation Parameters:")
    
    temperature = gkd_cfg.get("temperature", 2.0)
    logger.info(f"   Temperature: {temperature} (softens logits distribution)")
    
    lmbda = gkd_cfg.get("lmbda", 0.5)
    logger.info(f"   Lambda: {lmbda} (mix ratio between SFT and KD)")
    
    alpha = gkd_cfg.get("beta", 0.5)
    logger.info(f"   Alpha: {alpha} (fraction of student trajectories during training)")
    
    training_args = TrainingArguments(
        output_dir=output_dir,
        num_train_epochs=1,
        per_device_train_batch_size=2,
        gradient_accumulation_steps=8,
        learning_rate=2e-5,
        bf16=True,
        logging_steps=5,
        save_strategy="no",
        report_to="none"
    )
    
    trainer = GKDTrainer(
        model=student_model,
        teacher_model=mock_teacher,
        args=training_args,
        train_dataset=train_dataset,
        tokenizer=tokenizer,
        temperature=temperature,
        lmbda=lmbda,
        alpha=alpha,
    )
    
    logger.info("\nDistillation initialization finished (Simulated state).")


def main():
    config = load_config()
    explain_kl_divergence()
    run_gkd_pipeline(config)


if __name__ == "__main__":
    main()
